#!/usr/bin/env node
// Turns the web export into an installable, offline app
// (iPhone: Safari → Share → "Add to Home Screen"; Android/desktop: "Install app").
// Usage: node scripts/pwa.mjs dist /popote
import { createHash } from 'node:crypto';
import { copyFileSync, existsSync, readdirSync, readFileSync, renameSync, statSync, writeFileSync } from 'node:fs';
import { join, relative } from 'node:path';

const dir = process.argv[2] ?? 'dist';
const base = (process.argv[3] ?? '').replace(/\/$/, '');

const listFiles = (d, out = []) => {
  for (const f of readdirSync(d)) {
    const p = join(d, f);
    if (statSync(p).isDirectory()) listFiles(p, out);
    else out.push(p);
  }
  return out;
};

// ---- GitHub Pages refuses to deploy some paths the Expo export produces:
// a folder named node_modules (assets/node_modules/...) and file names with brackets ([id]-hash.js).
// Rename them and rewrite the references inside the bundles.
if (existsSync(join(dir, 'assets/node_modules'))) renameSync(join(dir, 'assets/node_modules'), join(dir, 'assets/vendor'));
const jsDir = join(dir, '_expo/static/js/web');
if (existsSync(jsDir)) {
  for (const f of readdirSync(jsDir)) {
    const m = f.match(/^\[(\w+)\]-(.*)$/);
    if (m) renameSync(join(jsDir, f), join(jsDir, `param-${m[1]}-${m[2]}`));
  }
}
for (const f of listFiles(dir).filter((p) => /\.(js|html|json|css)$/.test(p))) {
  const src = readFileSync(f, 'utf8');
  const out = src
    .split('/assets/node_modules/').join('/assets/vendor/')
    .replace(/(_expo\/static\/js\/web\/)\[(\w+)\]-/g, '$1param-$2-');
  if (out !== src) writeFileSync(f, out);
}

copyFileSync('assets/icon.png', join(dir, 'apple-touch-icon.png'));
copyFileSync('assets/icon.png', join(dir, 'icon-1024.png'));

writeFileSync(
  join(dir, 'manifest.webmanifest'),
  JSON.stringify(
    {
      name: 'Popote',
      short_name: 'Popote',
      description: 'Carnet de recettes libre : importer, cuisiner, planifier, faire les courses.',
      lang: 'fr',
      start_url: `${base}/`,
      scope: `${base}/`,
      display: 'standalone',
      orientation: 'portrait',
      background_color: '#FBF6EF',
      theme_color: '#FBF6EF',
      icons: [
        { src: `${base}/icon-1024.png`, sizes: '1024x1024', type: 'image/png', purpose: 'any' },
        { src: `${base}/icon-1024.png`, sizes: '1024x1024', type: 'image/png', purpose: 'maskable' },
      ],
    },
    null,
    2,
  ),
);

// ---- index.html: install tags + service worker registration ----
const tags = [
  `<link rel="manifest" href="${base}/manifest.webmanifest">`,
  `<link rel="apple-touch-icon" href="${base}/apple-touch-icon.png">`,
  '<meta name="apple-mobile-web-app-capable" content="yes">',
  '<meta name="mobile-web-app-capable" content="yes">',
  '<meta name="apple-mobile-web-app-title" content="Popote">',
  '<meta name="apple-mobile-web-app-status-bar-style" content="default">',
  '<meta name="theme-color" content="#FBF6EF" media="(prefers-color-scheme: light)">',
  '<meta name="theme-color" content="#1A1512" media="(prefers-color-scheme: dark)">',
  '<meta name="format-detection" content="telephone=no">',
  `<script>if('serviceWorker' in navigator){addEventListener('load',function(){navigator.serviceWorker.register('${base}/sw.js',{scope:'${base}/'})})}</script>`,
].join('\n    ');

const indexPath = join(dir, 'index.html');
let html = readFileSync(indexPath, 'utf8').replace('</head>', `    ${tags}\n  </head>`);
// keep the layout under the iPhone notch and home bar
html = html.replace(/<meta name="viewport" content="([^"]*)"/, (m, c) => (c.includes('viewport-fit') ? m : `<meta name="viewport" content="${c}, viewport-fit=cover"`));
writeFileSync(indexPath, html);
// GitHub Pages serves 404.html for unknown paths: reuse the app so deep links (/recipe/…) work.
writeFileSync(join(dir, '404.html'), html);

// ---- service worker: precache every file of the build, so the app opens offline ----
const files = listFiles(dir);
const urls = files
  .map((f) => relative(dir, f).split('\\').join('/'))
  .filter((f) => !['sw.js', '404.html', 'metadata.json'].includes(f))
  .map((f) => `${base}/${f}`);
const hash = createHash('sha256');
for (const f of files) hash.update(readFileSync(f));
const version = hash.digest('hex').slice(0, 12);

const sw = `// Generated by scripts/pwa.mjs
const CACHE = 'popote-${version}';
const BASE = '${base}';
const PRECACHE = ${JSON.stringify([`${base}/`, ...urls])};

self.addEventListener('install', (e) => {
  e.waitUntil(caches.open(CACHE).then((c) => c.addAll(PRECACHE)).then(() => self.skipWaiting()));
});

self.addEventListener('activate', (e) => {
  e.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((k) => k.startsWith('popote-') && k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim()),
  );
});

self.addEventListener('fetch', (e) => {
  const req = e.request;
  if (req.method !== 'GET') return;
  const url = new URL(req.url);
  if (url.origin !== location.origin) return; // recipe sites, AI APIs: always network
  if (req.mode === 'navigate') {
    // the app shell: fresh when online, cached when offline
    e.respondWith(fetch(req).catch(() => caches.match(BASE + '/index.html').then((r) => r || caches.match(BASE + '/'))));
    return;
  }
  e.respondWith(
    caches.match(req).then((hit) => hit || fetch(req).then((res) => {
      if (res.ok) { const copy = res.clone(); caches.open(CACHE).then((c) => c.put(req, copy)); }
      return res;
    })),
  );
});
`;
writeFileSync(join(dir, 'sw.js'), sw);
console.log(`PWA ready in ${dir}: ${urls.length} files precached (version ${version})`);
