const DICTS = { fr, en };

export function translate(lang: 'fr' | 'en', key: Key | (string & {}), params?: Record<string, string | number>): string {
  let s: string = DICTS[lang][key as Key] ?? fr[key as Key] ?? key;
  if (params) for (const [k, v] of Object.entries(params)) s = s.split(`{${k}}`).join(String(v));
  return s;
}

export function useT() {
  const lang = useStore((s) => s.settings.language);
  const t = (key: Key | (string & {}), params?: Record<string, string | number>) => translate(lang, key, params);
  return { t, lang };
}
